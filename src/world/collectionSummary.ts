import type { RuntimeObject, RuntimeSlot, RuntimeValue, TraceEvent } from '../contracts/runtime'
import type { Evidence, SceneCollection, ValueText, WorldAnchor } from '../contracts/world'
import { displayType } from './displayType'
import { notRecordedValue, valueText } from './valueText'
import {collectionEntryFace} from './collectionFace'

export interface CollectionSummaryContext {
  /** Applied normalized prefix, not a raw recorder sequence. */
  cursor: number
  eventSeq: (id: string) => number | null
  objects: Readonly<Record<string, RuntimeObject>>
  mutationEvent?: TraceEvent | null
}
const kinds = { LIST: 'List', SET: 'Set', MAP: 'Map', QUEUE: 'Queue', DEQUE: 'Deque' } as const

function prefixSeq(id: string | undefined, context: CollectionSummaryContext): number | null {
  if (id === undefined) return null
  const seq = context.eventSeq(id)
  return seq !== null && Number.isSafeInteger(seq) && seq >= 0 && seq < context.cursor ? seq : null
}
function future(id: string | undefined, context: CollectionSummaryContext): boolean {
  if (id === undefined) return false
  const seq = context.eventSeq(id)
  return seq !== null && seq >= context.cursor
}
function entryEvidence(object: RuntimeObject, slot: RuntimeSlot | undefined, context: CollectionSummaryContext): Evidence {
  const observedId = slot?.observedAt ?? object.observedAt
  const observedSeq = prefixSeq(observedId, context)
  const changedSeq = prefixSeq(slot?.changedAt, context)
  const eventIds = [...new Set([
    ...(observedId !== undefined && observedSeq !== null ? [observedId] : []),
    ...(slot?.changedAt !== undefined && changedSeq !== null ? [slot.changedAt] : []),
  ])]
  return {
    kind: observedSeq !== null ? 'observed' : 'unavailable',
    // observedAt is the latest observation in RuntimeState, not first-observed
    // history. Never invent the introduction ordinal of an entry.
    introducedSeq: null, changedSeq, eventIds,
    ...(observedSeq === null ? { unavailableReason: 'Collection entry observation event is not available at this prefix' } : {}),
  }
}
function capturedValue(value: RuntimeValue | undefined, context: CollectionSummaryContext): ValueText {
  if (value?.kind !== 'reference') return valueText(value, { context: 'object', objects: context.objects })
  const target = context.objects[value.objectId]
  if (target && future(target.allocatedAt, context)) return notRecordedValue('Reference target was not recorded at this prefix')
  if (target?.library?.kind === 'BOXED') {
    if (future(target.observedAt, context)) return notRecordedValue('Boxed value was not recorded at this prefix')
    return target.library.value === undefined || target.library.value.kind === 'reference'
      ? notRecordedValue('Boxed value was not captured')
      : valueText(target.library.value, { context: 'object', objects: context.objects })
  }
  return valueText(value, { context: 'object', objects: context.objects })
}

/** Captured previews only. No comparison of values, field-name guesses or inferred operations. */
export function collectionSummary(object: RuntimeObject, anchor: WorldAnchor, context: CollectionSummaryContext): SceneCollection | null {
  const summary = object.library
  if (!summary || !Object.hasOwn(kinds, summary.kind) || summary.size === undefined
    || !Number.isSafeInteger(summary.size) || summary.size < 0
    || !Number.isSafeInteger(context.cursor) || context.cursor <= 0
    || future(object.allocatedAt, context) || future(object.observedAt, context)) return null
  const collectionKind = kinds[summary.kind as keyof typeof kinds]
  const isMap = collectionKind === 'Map'
  if (isMap ? (summary.items?.length ?? 0) > 0 : (summary.entries?.length ?? 0) > 0) return null
  const count = isMap ? summary.entries?.length ?? 0 : summary.items?.length ?? 0
  // The reducer enforces this invariant. An inconsistent preview is fallback,
  // never silently clipped to fabricate a plausible collection snapshot.
  if (count > summary.size) return null
  const entries: SceneCollection['entries'][number][] = []
  const add = (index: number, rawValue: RuntimeValue, rawKey?: RuntimeValue): void => {
    // These are precisely the canonical slots generated by normalize/provenance.
    // Map keys and values retain separate canonical slots and visible chips.
    const slotId = isMap ? `${object.id}:summary:entry:${index}:value` : `${object.id}:summary:item:${index}`
    const value = capturedValue(rawValue, context)
    const geometry=collectionEntryFace(anchor,index,isMap),capturedPort=geometry?.value??null
    const port=value.kind==='reference'?capturedPort:null
    entries.push({
      slotId, value, port,
      ...(rawKey === undefined ? {} : { key: capturedValue(rawKey, context), keySlotId: `${object.id}:summary:entry:${index}:key`, keyPort: capturedValue(rawKey,context).kind==='reference'?geometry?.key??null:null }),
      evidence: entryEvidence(object, object.fields[slotId], context),
    })
  }
  if (isMap) summary.entries?.forEach((entry, index) => add(index, entry.value, entry.key))
  else summary.items?.forEach((value, index) => add(index, value))
  const observationSeq = prefixSeq(object.observedAt, context)
  const allocationSeq = prefixSeq(object.allocatedAt, context)
  const evidence: Evidence = {
    kind: observationSeq === null ? 'unavailable' : 'observed', introducedSeq: allocationSeq,
    changedSeq: null,
    eventIds: [...new Set([
      ...(allocationSeq !== null ? [object.allocatedAt] : []),
      ...(object.observedAt !== undefined && observationSeq !== null ? [object.observedAt] : []),
    ])],
    ...(summary.truncated ? { derivation: `Captured preview marked truncated${summary.reason ? `: ${summary.reason}` : ''}` } : {}),
    ...(entries.length < summary.size || observationSeq === null ? {
      unavailableReason: summary.reason ?? (entries.length < summary.size
        ? `${summary.size - entries.length} collection entries were not recorded`
        : 'Collection observation event is not available at this prefix'),
    } : {}),
  }
  return {
    kind: 'collection', id: object.id, displayId: object.displayId, title: displayType(object.className),
    collectionKind, size: summary.size, recordedEntries: entries.length, entries,
    // Current TraceEvent/ExecutionFact vocabularies record observations and
    // calls, but no proven collection add/remove/put/poll result or entry index.
    mutation: null, anchor, ownership: object.metadata?.ownership ?? (anchor.region==='heap'?'PROJECT':'LIBRARY'), evidence,
  }
}
