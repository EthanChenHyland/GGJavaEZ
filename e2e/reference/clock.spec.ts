import {expect,test} from '@playwright/test'
import {browserErrors,runFixture,stopOwnedSession} from './harness'
test.afterEach(async({request})=>stopOwnedSession(request))
test('QA steps the real camera clock while preserving the recording cursor, selection and anchors',async({page,request})=>{
 test.setTimeout(60000)
 const errors=browserErrors(page)
 await runFixture(page,request,'domain')
 const slider=page.getByRole('slider',{name:'Recorded execution position'});await slider.focus();await page.keyboard.press('End')
 await page.getByRole('button',{name:'Home',exact:true}).click();await page.evaluate(()=>window.__ggjavaezWorld!.ready())
 await page.locator('.world-canvas').focus();await page.keyboard.press('Tab')
 const before=await page.evaluate(()=>({pose:window.__ggjavaezQA!.cameraPose(),recording:window.__ggjavaezWorld!.scene().recordingId,cursor:window.__ggjavaezWorld!.scene().cursor,selection:window.__ggjavaezWorld!.selection(),anchors:Object.fromEntries(Object.entries(window.__ggjavaezWorld!.scene().entities).map(([id,node])=>[id,node.anchor]))}))
 await page.evaluate(()=>window.__ggjavaezQA!.clock.step(0))
 await page.getByRole('button',{name:'Focus',exact:true}).click()
 const step=async(ms:number)=>page.evaluate(async(ms)=>{window.__ggjavaezQA!.clock.step(ms);await new Promise<void>(resolve=>requestAnimationFrame(()=>requestAnimationFrame(()=>resolve())));return window.__ggjavaezQA!.cameraPose()},ms)
 await step(0)
 const middle=await step(450),end=await step(600)
 expect(middle).not.toEqual(before.pose);expect(end).not.toEqual(middle)
 const after=await page.evaluate(()=>({recording:window.__ggjavaezWorld!.scene().recordingId,cursor:window.__ggjavaezWorld!.scene().cursor,selection:window.__ggjavaezWorld!.selection(),anchors:Object.fromEntries(Object.entries(window.__ggjavaezWorld!.scene().entities).map(([id,node])=>[id,node.anchor]))}))
 expect(after).toEqual({recording:before.recording,cursor:before.cursor,selection:before.selection,anchors:before.anchors})
 await page.getByRole('button',{name:'Home',exact:true}).click();await step(0);await step(1000)
 await page.evaluate(()=>window.__ggjavaezQA!.clock.resume());await page.evaluate(()=>window.__ggjavaezWorld!.ready())
 const projection=await page.evaluate(()=>window.__ggjavaezQA!.worldProjection())
 expect(projection?.stack).not.toBeNull();expect(projection?.heap).not.toBeNull()
 expect(errors).toEqual([])
})
