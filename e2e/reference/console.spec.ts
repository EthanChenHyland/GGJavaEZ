import { expect, test } from '@playwright/test'
import { writeFile } from 'node:fs/promises'
import { browserErrors, currentSession } from './harness'
import type {} from './fixtures/console'

test('million-line Console has bounded rows, exact detail and first/last presentation within 200 ms', async ({ page }) => {
  const errors = browserErrors(page)
  await page.goto('/e2e/reference/fixtures/console.html')
  const list = page.getByRole('list', { name: 'Captured output rows' })
  const measurements: {elapsed:number;offscreen:number;first:string|null|undefined;last:string|null|undefined;text:string;target:string}[] = []
  await expect(list.getByRole('listitem').last()).toHaveAttribute('aria-posinset', '1000000')
  for (const target of ['First', 'Last', 'First', 'Last']) {
    const result = await page.evaluate(async target => {
      const start = performance.now()
      ;(Array.from(document.querySelectorAll('button')).find(button => button.textContent === target)!).click()
      await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))
      const host = document.querySelector('.console-lines-scroll')!, area = host.getBoundingClientRect()
      const rows = Array.from(host.querySelectorAll('[role=listitem]'))
      const visible = rows.filter(row => { const rect = row.getBoundingClientRect(); return rect.bottom > area.top && rect.top < area.bottom })
      return { elapsed: performance.now() - start, offscreen: rows.length - visible.length,
        first: rows[0]?.getAttribute('aria-posinset'), last: rows.at(-1)?.getAttribute('aria-posinset'), text: visible.map(row => row.textContent).join('') }
    }, target)
    expect(result.elapsed).toBeLessThanOrEqual(200); expect(result.offscreen).toBeLessThanOrEqual(200)
    expect(result.text).toContain(target === 'First' ? 'first' : 'last')
    expect(target === 'First' ? result.first : result.last).toBe(target === 'First' ? '1' : '1000000')
    measurements.push({...result,target})
  }
  await writeFile('.ggjavaez/qa/reference-exact/console-million-measurements.json',JSON.stringify({fixture:'isolated production ConsoleLines',realJvm:false,lineCount:1000000,viewport:page.viewportSize(),measurements},null,2)+'\n')
  await page.screenshot({path:'.ggjavaez/qa/reference-exact/console-million.png'})
  await page.getByLabel('Captured output row', { exact: true }).fill('500000')
  await page.getByLabel('Captured output row', { exact: true }).press('Enter')
  await expect(list.locator('[aria-posinset="500000"]')).toBeVisible()
  await page.getByRole('button', { name: 'First', exact: true }).click()
  const scroll = await list.evaluate(node => { node.scrollTop = 72; node.dispatchEvent(new Event('scroll', {bubbles:true})); return node.scrollTop })
  await page.evaluate(() => window.consoleFixture.set([{ key: 'pipe', channel: 'stdout', text: 'first\n' + 'middle\n'.repeat(999998) + 'last\ntail' }]))
  expect(await list.evaluate(node => node.scrollTop)).toBe(scroll)
  await page.getByRole('button', { name: 'Last', exact: true }).click()
  await expect(list.locator('[aria-posinset="1000001"]')).toContainText('tail')
  await list.dispatchEvent('pointerdown')
  await page.evaluate(() => window.consoleFixture.set([{ key: 'replacement', channel: 'stderr', text: '\r\n' + '<literal>&😀'.repeat(30) + '\r\n' }]))
  await page.getByRole('button', { name: 'Open Captured output row 2', exact: true }).click()
  const detail = page.getByRole('region', { name: 'Exact Captured output row 2' })
  expect(await detail.locator('pre').textContent()).toBe('<literal>&😀'.repeat(30) + '\r\n')
  expect(await list.locator('.ide-console-stderr').first().evaluate(node => getComputedStyle(node).color)).toBe('rgb(255, 138, 91)')
  await page.screenshot({ path: '.ggjavaez/qa/reference-exact/console-million-detail.png' })
  await page.evaluate(() => window.consoleFixture.set([{ key: 'replacement', channel: 'stderr', text: 'first small\n' + 'new\n'.repeat(8998) + 'end\n' }]))
  await expect(list.getByRole('listitem').first()).toHaveAttribute('aria-posinset','1')
  await expect(list.locator('[aria-posinset="1"]')).toBeVisible()
  await expect(detail).toHaveCount(0)
  expect(errors).toEqual([])
})

for (const viewport of [{ width: 1440, height: 900 }, { width: 760, height: 900 }]) test(`real JVM Console preserves recorder order, pipe channels and stdin ${viewport.width}x${viewport.height}`, async ({page, request}) => {
  test.setTimeout(60000); await page.setViewportSize(viewport)
  const errors = browserErrors(page)
  const response = await request.post('/api/projects/import', { data: { name: `Console ${Date.now()}`, files: [{ path: 'Main.java', content: 'import java.util.Scanner; public class Main { public static void main(String[] args) { System.out.print("prompt "); System.out.println("ready"); System.err.println("warning only"); String name = new Scanner(System.in).nextLine(); System.out.println("Hello " + name); } }\n' }] } })
  expect(response.ok()).toBe(true); const {id} = await response.json()
  await page.addInitScript(id => localStorage.setItem('ggjavaez:project', id), id)
  await page.goto('/?qa=1'); await expect(page.getByRole('button', {name:'Run',exact:true})).toBeEnabled()
  await page.getByRole('button', {name:'Run',exact:true}).click()
  await expect.poll(async () => {const session = await currentSession(request); return session && session.projectId === id ? session.phase : null}).toBe('WAITING_FOR_INPUT')
  await expect(page.getByLabel('Console input', {exact:true})).toBeVisible()
  await page.getByRole('button', {name:'CONSOLE',exact:true}).click()
  const console = page.getByLabel('Program console', {exact:true})
  await expect(console).toContainText('prompt ready'); await expect(console).toContainText('warning only')
  const session = await currentSession(request)
  expect(session?.stdout).toBe('prompt ready\n'); expect(session?.stderr).toBe('warning only\n')
  await page.getByLabel('Console input', {exact:true}).fill('Ada & <exact>')
  await page.getByLabel('Console input', {exact:true}).press('Enter')
  await expect.poll(async () => { const current = await currentSession(request); return current?.id === session!.id ? current.phase : null }).toBe('COMPLETED')
  await page.getByRole('button', {name:'CONSOLE',exact:true}).click()
  await expect(console).toContainText('Hello Ada & <exact>')
  await console.evaluate(node => { node.scrollTop = 0 })
  await expect(console.getByRole('list', {name:'Recorded console rows'}).locator('[aria-posinset="1"]')).toBeVisible()
  await page.screenshot({path:`.ggjavaez/qa/reference-exact/console-real-${viewport.width}x${viewport.height}.png`})
  await page.locator('.ide-console-terminal summary').click()
  await expect(console).toContainText('cross-channel order not recorded')
  await expect(console.getByRole('list', {name:'stdout rows'})).toContainText('Hello Ada & <exact>')
  await expect(console.getByRole('list', {name:'stderr rows'})).toContainText('warning only')
  await console.getByRole('list', {name:'stderr rows'}).scrollIntoViewIfNeeded()
  await expect(console.getByRole('list', {name:'stderr rows'}).getByRole('listitem')).toBeVisible()
  const last = await currentSession(request)
  expect(last?.stdout).toBe('prompt ready\nHello Ada & <exact>\n'); expect(last?.stderr).toBe('warning only\n')
  expect(await console.locator('[role=listitem]').count()).toBeLessThan(200)
  await page.screenshot({path:`.ggjavaez/qa/reference-exact/console-pipes-${viewport.width}x${viewport.height}.png`})
  const slider = page.getByRole('slider', {name:'Recorded execution position',exact:true})
  await slider.focus(); await page.keyboard.press('Home')
  await expect(console.getByRole('list', {name:'Recorded console rows'}).getByRole('listitem')).toHaveCount(0)
  await expect(console.getByRole('list', {name:'stdout rows'})).toContainText('Hello Ada & <exact>')
  await slider.focus(); await page.keyboard.press('End')
  const first = console.getByRole('button', {name:'Open Recorded console row 1',exact:true})
  await first.click()
  expect(await console.getByRole('region', {name:'Exact Recorded console row 1'}).locator('pre').textContent()).toBe('prompt ready\n')
  expect(errors).toEqual([])
})
