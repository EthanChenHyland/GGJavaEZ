import { expect, test } from '@playwright/test'
const sizes = [{width:1728,height:1117},{width:1440,height:900},{width:1280,height:800},{width:760,height:900},{width:1440,height:650}]
test('one viewport world and token shell geometry recompose at all five target sizes', async ({page}) => {
  await page.goto('/examples?qa=1')
  await expect(page.locator('.world-canvas canvas')).toHaveCount(1)
  const identity = await page.locator('.world-canvas canvas').evaluate(node => { node.setAttribute('data-same-canvas','verified'); return node.getAttribute('data-same-canvas') })
  for (const size of sizes) {
    await page.setViewportSize(size)
    await expect(page.locator('.shell')).toHaveAttribute('data-viewport',size.width<1024?'NARROW':size.height<760?'SHORT':size.width>=1600?'WIDE':'STANDARD')
    await expect.poll(async () => (await page.locator('.world-timeline').boundingBox())!.x).toBeCloseTo(size.width*.009,0)
    const rect = await page.locator('.world-timeline').boundingBox()
    expect(rect).not.toBeNull()
    expect(rect!.x).toBeCloseTo(size.width*.009,0)
    expect(rect!.width).toBeCloseTo(size.width*.982,0)
    expect(rect!.y+rect!.height).toBeCloseTo(size.height*.975,0)
    expect(await page.locator('.world-canvas canvas').getAttribute('data-same-canvas')).toBe(identity)
    expect(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
})
test('real Run and failed rebuild preserve canvas, recording, history and runtime identities', async ({page,request}) => {
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));page.on('console',message=>{if(message.type()==='error')errors.push(message.text())})
  const source = 'public class Main { public static void main(String[] args) { Item item = new Item(); item.age = 18; System.out.println("AGE " + item.age); } } class Item { int age; }\n'
  const imported=await request.post('/api/projects/import',{data:{name:`Reference shell ${Date.now()}`,files:[{path:'Main.java',content:source}]}})
  expect(imported.ok()).toBe(true)
  const {id}=await imported.json()
  await page.addInitScript(id=>localStorage.setItem('ggjavaez:project',id),id)
  await page.goto('/?qa=1')
  await expect(page.locator('.monaco-editor')).toBeVisible()
  await page.locator('.world-canvas canvas').evaluate(node=>node.setAttribute('data-same-canvas','verified'))
  await page.getByRole('button',{name:'Run',exact:true}).click()
  await expect(page.locator('.shell-state')).toContainText('Completed',{timeout:45000})
  const completed = await (await request.get('/api/execution/current')).json()
  await expect(page.locator('.world-canvas canvas')).toHaveAttribute('data-same-canvas','verified')
  const timeline=page.getByRole('slider',{name:'Recorded execution position'})
  // Process completion metadata can arrive before retained raw pages publish.
  await expect.poll(async()=>Number(await timeline.getAttribute('aria-valuemax'))).toBeGreaterThan(0)
  const count=Number(await timeline.getAttribute('aria-valuemax'))
  expect(count).toBeGreaterThan(0)
  await timeline.focus()
  await page.keyboard.press('Home')
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('ArrowRight')
  await expect(timeline).toHaveAttribute('aria-valuenow','2')
  const editor=page.locator('.monaco-editor').first()
  await editor.click()
  await page.keyboard.press('ControlOrMeta+A')
  await page.keyboard.insertText('public class Main { invalid syntax }\n')
  await page.getByRole('button',{name:'Run',exact:true}).click()
  await expect(page.locator('.shell-state')).toContainText('Build failed',{timeout:45000})
  await expect(timeline).toHaveAttribute('aria-valuenow','2')
  await expect(timeline).toHaveAttribute('aria-valuemax',String(count))
  await expect(page.locator('.world-canvas canvas')).toHaveAttribute('data-same-canvas','verified')
  await expect(page.getByRole('status').filter({hasText:'Previous run'})).toBeVisible()
  const failed = await (await request.get('/api/execution/current')).json()
  expect(failed.id).not.toBe(completed.id); expect(failed.failureKind).toBe('build')
  await page.getByRole('button',{name:'CONSOLE',exact:true}).click()
  const oldConsole=page.getByRole('region',{name:'Previous run console',exact:true})
  const attempt=page.getByRole('region',{name:'Current attempt console',exact:true})
  await expect(oldConsole).toHaveAttribute('data-console-session',completed.id)
  await expect(attempt).toHaveAttribute('data-console-session',failed.id)
  await expect(oldConsole.getByRole('list',{name:'Recorded console rows'}).getByRole('listitem')).toHaveCount(0)
  await timeline.focus();await page.keyboard.press('End')
  await expect(oldConsole.getByRole('list',{name:'Recorded console rows'})).toContainText('AGE 18')
  await oldConsole.locator('.ide-console-terminal summary').click()
  await expect(oldConsole.getByRole('list',{name:'stdout rows'})).toContainText('AGE 18')
  await expect(attempt.getByRole('list',{name:'Build output rows'})).toContainText('Main.java')
  await page.screenshot({path:'.ggjavaez/qa/reference-exact/console-retained-failed-build.png'})
  await oldConsole.locator('.ide-console-terminal summary').click()
  await attempt.getByRole('list',{name:'Build output rows'}).scrollIntoViewIfNeeded()
  await expect(attempt.getByRole('list',{name:'Build output rows'}).getByRole('listitem').first()).toBeVisible()
  await expect(attempt).toContainText('No program output · build failed')
  await page.screenshot({path:'.ggjavaez/qa/reference-exact/console-new-failed-attempt.png'})
  await oldConsole.locator('.ide-console-terminal summary').click()
  await timeline.focus();await page.keyboard.press('Home')
  await expect(oldConsole.getByRole('list',{name:'Recorded console rows'}).getByRole('listitem')).toHaveCount(0)
  await expect(oldConsole.getByRole('list',{name:'stdout rows'})).toContainText('AGE 18')
  await expect(oldConsole).toHaveAttribute('data-console-session',completed.id)
  await expect(attempt).toHaveAttribute('data-console-session',failed.id)
  expect(errors).toEqual([])
})
