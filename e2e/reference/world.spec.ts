import {expect,test,type Page} from '@playwright/test'
import type {SceneModel} from '../../src/contracts/world'
import type {Selection} from '../../src/contracts/interaction'
type Qa={ready():Promise<void>;cameraPose():{position:number[];target:number[]};selection():Selection;scene():SceneModel}
const qa=(page:Page)=>page.evaluate(()=>((window as unknown as {__ggjavaezQA:Qa}).__ggjavaezQA).ready())
const pose=(page:Page)=>page.evaluate(()=>((window as unknown as {__ggjavaezQA:Qa}).__ggjavaezQA).cameraPose())
const selection=(page:Page)=>page.evaluate(()=>((window as unknown as {__ggjavaezQA:Qa}).__ggjavaezQA).selection())
const errorLog=(page:Page)=>{const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));page.on('console',message=>{if(message.type()==='error')errors.push(message.text())});return errors}

test('semantic timeline keyboard reaches both boundaries and highlights captured source',async({page})=>{
 const errors=errorLog(page)
 await page.goto('/examples?qa=1')
 const slider=page.getByRole('slider',{name:'Recorded execution position'})
 await slider.focus();await page.keyboard.press('End');await qa(page)
 const count=Number(await slider.getAttribute('aria-valuemax'))
 expect(count).toBeGreaterThan(0);await expect(slider).toHaveAttribute('aria-valuenow',String(count))
 await page.keyboard.press('Home');await expect(slider).toHaveAttribute('aria-valuenow','0')
 await expect(slider).toHaveAttribute('aria-valuetext','Before execution')
 await page.keyboard.press('ArrowRight');await expect(slider).toHaveAttribute('aria-valuenow','1')
 await expect(page.locator('.ide-editor-foot')).toContainText('Recorded source · Main.java')
 await expect(page.locator('.ide-editor-foot')).toContainText('22 lines')
 await expect(page.locator('.executing-line')).toHaveCount(1)
 await expect(slider).toHaveAttribute('type','range')
 await slider.focus();await page.keyboard.press('Home');await qa(page)
 const before=(await slider.boundingBox())!,middle=Math.floor(count/2)
 await slider.fill(String(middle));await expect(slider).toHaveAttribute('aria-valuenow',String(middle));await qa(page)
 expect(await page.evaluate(()=>window.__ggjavaezWorld!.scene().cursor)).toBe(middle)
 const after=(await slider.boundingBox())!
 expect(after.x).toBeCloseTo(before.x,4);expect(after.width).toBeCloseTo(before.width,4)
 await page.mouse.move(after.x+after.width*.25,after.y+after.height/2);await page.mouse.down()
 await expect(page.getByRole('region',{name:'Execution timeline'})).toHaveAttribute('data-scrubbing','true')
 await page.mouse.move(after.x+after.width*.75,after.y+after.height/2);await page.mouse.up();await qa(page)
 await expect(page.getByRole('region',{name:'Execution timeline'})).toHaveAttribute('data-scrubbing','false')
 expect(Number(await slider.getAttribute('aria-valuenow'))).toBeGreaterThan(middle)
 expect(errors).toEqual([])
})

test('keyboard selection and Trace preserve the camera; Focus returns to its original pose',async({page})=>{
 const errors=errorLog(page)
 await page.goto('/examples?qa=1')
 const slider=page.getByRole('slider',{name:'Recorded execution position'})
 await slider.focus();await page.keyboard.press('End')
 await page.getByRole('button',{name:'Home',exact:true}).click();await qa(page)
 const original=await pose(page),cursor=await slider.getAttribute('aria-valuenow')
 await expect.poll(async()=>page.getByRole('option').count()).toBeGreaterThan(0)
 await page.getByRole('application',{name:'Three-dimensional Java runtime world'}).focus()
 await page.keyboard.press('Tab')
 await expect(page.getByRole('listbox',{name:'Runtime entities'})).toBeFocused()
 const selected=await selection(page);expect(selected).not.toBeNull()
 expect(await pose(page)).toEqual(original)
 await page.getByRole('button',{name:'Trace',exact:true}).click();await qa(page)
 expect(await pose(page)).toEqual(original);expect(await selection(page)).toEqual(selected)
 await expect(slider).toHaveAttribute('aria-valuenow',cursor!)
 await expect(page.getByRole('group',{name:'Trace scope'})).toBeVisible()
 await page.getByRole('button',{name:'Focus',exact:true}).click();await qa(page)
 const focused=await pose(page);expect(focused).not.toEqual(original)
 await expect(page.locator('.shell-modes button[aria-pressed="true"]')).toHaveCount(1)
 await expect(page.getByRole('button',{name:'Focus',exact:true})).toHaveAttribute('aria-pressed','true')
 await page.getByRole('button',{name:'Focus',exact:true}).click();await qa(page)
 const restored=await pose(page)
 for(const key of ['position','target'] as const)for(let axis=0;axis<3;axis++)expect(restored[key][axis]).toBeCloseTo(original[key][axis],5)
 expect(await selection(page)).toEqual(selected)
 await expect(page.getByRole('button',{name:'Trace',exact:true})).toHaveAttribute('aria-pressed','true')
 expect(errors).toEqual([])
})

test('an empty recording consumes transport keys without starting playback',async({page})=>{
 const errors=errorLog(page)
 await page.addInitScript(()=>localStorage.removeItem('ggjavaez:project'))
 await page.goto('/?qa=1')
 const slider=page.getByRole('slider',{name:'Recorded execution position'})
 await expect(slider).toHaveAttribute('aria-disabled','true')
 await slider.focus()
 for(const key of ['Space','ArrowRight','ArrowLeft','End','Home'])await page.keyboard.press(key)
 await expect(slider).toHaveAttribute('aria-valuenow','0')
 await expect(page.getByRole('button',{name:'Play recorded execution',exact:true})).toHaveAttribute('aria-disabled','true')
 expect(errors).toEqual([])
})
