import { expect, test, type APIRequestContext, type Page } from '@playwright/test'

test.use({ permissions: ['clipboard-read', 'clipboard-write'] })

const files = [
  { path: 'Main.java', content: 'class Main {}\n' },
  { path: 'accounts/Alpha.java', content: 'package accounts; class Alpha {}\n' },
  { path: 'accounts/Beta.java', content: 'package accounts; class Beta {}\n' },
  { path: 'accounts/Gamma.java', content: 'package accounts; class Gamma {}\n' },
]
const paths = files.map((file) => file.path)
const dirtyBeta = 'package accounts; class Beta { int unsaved = 7; }\n'

async function openProject(page: Page, request: APIRequestContext) {
  const current = await (await request.get('/api/execution/current?transport=delta')).json()
  expect(current && ['BUILDING', 'STARTING', 'RUNNING', 'WAITING_FOR_INPUT', 'PAUSED'].includes(current.phase), 'Use the serialized browser window after the current execution finishes').toBeFalsy()
  // Real managed source files, with no Run, Debug or build command in this suite.
  const response = await request.post('/api/projects/import', { data: { name: `Phase5 shell ${Date.now()}`, files } })
  expect(response.ok(), await response.text()).toBe(true)
  const { id } = await response.json() as { id: string }
  await page.addInitScript(({ id, paths }) => {
    localStorage.setItem('ggjavaez:project', id)
    localStorage.setItem('ggjavaez:m8:explorer', 'open')
    localStorage.setItem('ggjavaez:p5:source-width', '38')
    localStorage.setItem(`ggjavaez:session:${id}`, JSON.stringify({ paths, active: 'accounts/Gamma.java' }))
  }, { id, paths })
  await page.goto('/ide')
  await expect(page.locator('.ide-tab')).toHaveCount(4)
  await expect(page.locator('.monaco-editor')).toBeVisible()
  await expect(page.getByRole('tree', { name: 'Project explorer' })).toBeVisible()
  return id
}
const tab = (page: Page, path: string) => page.getByRole('tab').filter({ has: page.getByRole('button', { name: `Close ${path}`, exact: true }) })
const row = (page: Page, path: string) => page.locator(`.ide-tree-name[title="${path}"]`)
async function tabMenu(page: Page, path: string) {
  await tab(page, path).click({ button: 'right' })
  const menu = page.getByRole('menu', { name: `Tab actions for ${path}`, exact: true })
  await expect(menu).toBeVisible()
  return menu
}
async function chooseTabAction(page: Page, path: string, name: string) {
  const menu = await tabMenu(page, path)
  await menu.getByRole('menuitem', { name, exact: true }).click()
  await expect(menu).toHaveCount(0)
}
async function makeBetaDirty(page: Page) {
  await tab(page, 'accounts/Beta.java').locator('button').first().click()
  await page.locator('.monaco-editor').click()
  await page.keyboard.press('ControlOrMeta+A')
  await page.keyboard.insertText(dirtyBeta)
  await expect(tab(page, 'accounts/Beta.java').locator('.ide-dirty')).toBeVisible()
  await tab(page, 'accounts/Gamma.java').locator('button').first().click()
}

test('folder/file menus Reveal and Copy the explicit target; keyboard dismissal restores focus', async ({ page, request }) => {
  await openProject(page, request)
  const folder = row(page, 'accounts')
  await folder.click({ button: 'right' })
  const menu = page.getByRole('menu', { name: 'Actions for accounts', exact: true })
  await expect(menu.getByRole('menuitem')).toHaveText(['New File', 'New Java Class', 'New Folder', 'Rename', 'Delete', 'Copy Path', 'Reveal in Explorer'])
  await expect(menu.getByRole('menuitem', { name: 'New File', exact: true })).toBeFocused()
  await page.keyboard.press('End')
  await expect(menu.getByRole('menuitem', { name: 'Reveal in Explorer', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(menu.getByRole('menuitem', { name: 'New File', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(menu).toHaveCount(0)
  await expect(folder).toBeFocused()
  await folder.press('Shift+F10')
  await menu.getByRole('menuitem', { name: 'Copy Path', exact: true }).click()
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe('accounts')
  await folder.click({ button: 'right' })
  await menu.getByRole('menuitem', { name: 'Reveal in Explorer', exact: true }).click()
  await expect(menu).toHaveCount(0)
  await expect(folder).toBeFocused()
  await expect(tab(page, 'accounts/Gamma.java')).toHaveAttribute('aria-selected', 'true')

  await row(page, 'accounts/Alpha.java').click({ button: 'right' })
  const fileMenu = page.getByRole('menu', { name: 'Actions for accounts/Alpha.java', exact: true })
  await expect(fileMenu.getByRole('menuitem')).toHaveText(['Open', 'Rename', 'Delete', 'Copy Path', 'Reveal in Explorer'])
  await fileMenu.getByRole('menuitem', { name: 'Open', exact: true }).click()
  await expect(tab(page, 'accounts/Alpha.java')).toHaveAttribute('aria-selected', 'true')
})

test('seven tab actions retain the clicked inactive target for Copy, Reveal, Rename and Close', async ({ page, request }) => {
  await openProject(page, request)
  const menu = await tabMenu(page, 'accounts/Alpha.java')
  await expect(menu.getByRole('menuitem')).toHaveText(['Close', 'Close Others', 'Close to Right', 'Close Saved', 'Rename', 'Reveal in Explorer', 'Copy Path'])
  await page.keyboard.press('End')
  await expect(menu.getByRole('menuitem', { name: 'Copy Path', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(menu.getByRole('menuitem', { name: 'Close', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(menu).toHaveCount(0)
  await chooseTabAction(page, 'accounts/Alpha.java', 'Copy Path')
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe('accounts/Alpha.java')
  await row(page, 'accounts').click()
  await expect(row(page, 'accounts/Alpha.java')).toHaveCount(0)
  await chooseTabAction(page, 'accounts/Alpha.java', 'Reveal in Explorer')
  await expect(row(page, 'accounts/Alpha.java')).toBeVisible()
  await expect(row(page, 'accounts/Alpha.java')).toBeFocused()
  await chooseTabAction(page, 'accounts/Alpha.java', 'Rename')
  const rename = page.getByRole('dialog', { name: 'Rename', exact: true })
  await expect(rename.getByRole('textbox')).toHaveValue('accounts/Alpha.java')
  await rename.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(tab(page, 'accounts/Gamma.java')).toHaveAttribute('aria-selected', 'true')
  await chooseTabAction(page, 'accounts/Alpha.java', 'Close')
  await expect(tab(page, 'accounts/Alpha.java')).toHaveCount(0)
  await expect(page.locator('.ide-tab')).toHaveCount(3)
  await expect(tab(page, 'accounts/Gamma.java')).toHaveAttribute('aria-selected', 'true')
})

test('Close to Right uses tab order and Close Others Cancel preserves all dirty data', async ({ page, request }) => {
  const id = await openProject(page, request)
  await makeBetaDirty(page)
  await chooseTabAction(page, 'accounts/Gamma.java', 'Close to Right')
  await expect(page.locator('.ide-tab')).toHaveCount(4)
  await chooseTabAction(page, 'accounts/Beta.java', 'Close to Right')
  await expect(tab(page, 'accounts/Gamma.java')).toHaveCount(0)
  await expect(page.locator('.ide-tab')).toHaveCount(3)
  await expect(tab(page, 'accounts/Beta.java').locator('.ide-dirty')).toBeVisible()
  await chooseTabAction(page, 'accounts/Alpha.java', 'Close Others')
  const decision = page.getByRole('dialog', { name: 'Unsaved changes', exact: true })
  await decision.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.locator('.ide-tab')).toHaveCount(3)
  await expect(tab(page, 'accounts/Beta.java').locator('.ide-dirty')).toBeVisible()
  expect((await (await request.get(`/api/projects/${id}/files?path=accounts%2FBeta.java`)).json()).content).toBe(files[2].content)
  await chooseTabAction(page, 'accounts/Alpha.java', 'Close Others')
  await decision.getByRole('button', { name: 'Discard', exact: true }).click()
  await expect(page.locator('.ide-tab')).toHaveCount(1)
  await expect(tab(page, 'accounts/Alpha.java')).toHaveAttribute('aria-selected', 'true')
  expect((await (await request.get(`/api/projects/${id}/files?path=accounts%2FBeta.java`)).json()).content).toBe(files[2].content)
})

test('Close Saved keeps dirty Monaco text and its recovery draft without prompting', async ({ page, request }) => {
  const id = await openProject(page, request)
  await makeBetaDirty(page)
  await chooseTabAction(page, 'accounts/Alpha.java', 'Close Saved')
  await expect(page.locator('.ide-tab')).toHaveCount(1)
  await expect(tab(page, 'accounts/Beta.java')).toHaveAttribute('aria-selected', 'true')
  await expect(tab(page, 'accounts/Beta.java').locator('.ide-dirty')).toBeVisible()
  await expect(page.getByRole('dialog', { name: 'Unsaved changes', exact: true })).toHaveCount(0)
  await expect.poll(() => page.evaluate((id) => JSON.parse(localStorage.getItem(`ggjavaez:draft:${id}:accounts/Beta.java`) ?? 'null')?.draft, id)).toBe(dirtyBeta)
  expect((await (await request.get(`/api/projects/${id}/files?path=accounts%2FBeta.java`)).json()).content).toBe(files[2].content)
})

test('Quick Open fuzzy paths and command palette work from Monaco with keyboard lists', async ({ page, request }) => {
  await openProject(page, request)
  await page.locator('.monaco-editor').click()
  await page.keyboard.press('ControlOrMeta+P')
  const quick = page.getByRole('dialog', { name: 'Quick Open', exact: true })
  const search = quick.getByRole('combobox', { name: 'Search project files', exact: true })
  await expect(search).toBeFocused()
  await search.fill('accts btj')
  await expect(quick.getByRole('option')).toHaveCount(1)
  await expect(quick.getByRole('option')).toContainText('Beta.java')
  await search.press('Enter')
  await expect(quick).toHaveCount(0)
  await expect(tab(page, 'accounts/Beta.java')).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('ControlOrMeta+Shift+P')
  const palette = page.getByRole('dialog', { name: 'Command Palette', exact: true })
  const command = palette.getByRole('combobox', { name: 'Search commands', exact: true })
  await expect(command).toBeFocused()
  await command.fill('debug.stepInto')
  const disabled = palette.getByRole('option', { name: /Step Into/ })
  await expect(disabled).toHaveAttribute('aria-disabled', 'true')
  await expect(disabled).toContainText('Stepping requires a paused debugger')
  await command.press('Enter')
  await expect(palette).toBeVisible()
  await command.fill('workbench.console')
  await expect(palette.getByRole('option')).toHaveCount(1)
  await command.press('Enter')
  await expect(palette).toHaveCount(0)
  await expect(page.locator('.ide-shell')).toHaveClass(/ide-shell--bottom-open/)
  await expect(page.locator('.ide-console')).toBeVisible()
  await page.keyboard.press('ControlOrMeta+Shift+P')
  await command.fill('workbench.source')
  await command.press('Enter')
  await expect(page.locator('.monaco-editor')).not.toBeVisible()
  await page.keyboard.press('ControlOrMeta+P')
  await search.fill('accts alj')
  await expect(quick.getByRole('option')).toHaveCount(1)
  await search.press('Enter')
  await expect(page.locator('.monaco-editor')).toBeVisible()
  await expect(tab(page, 'accounts/Alpha.java')).toHaveAttribute('aria-selected', 'true')
  const sourceTab = tab(page, 'accounts/Alpha.java').locator('button').first()
  await sourceTab.focus()
  await page.keyboard.press('ControlOrMeta+P')
  await search.fill('missingFileZzx')
  await expect(quick.getByRole('option')).toHaveCount(0)
  await search.press('Enter')
  await expect(quick).toBeVisible()
  await search.fill('java')
  await search.press('End')
  await expect(quick.getByRole('option').last()).toHaveAttribute('aria-selected', 'true')
  await search.press('ArrowDown')
  await expect(quick.getByRole('option').first()).toHaveAttribute('aria-selected', 'true')
  await search.press('Escape')
  await expect(quick).toHaveCount(0)
  await expect(sourceTab).toBeFocused()
})

test('New Java Class uses the selected real package and keeps invalid input correctable', async ({ page, request }) => {
  const id = await openProject(page, request)
  await expect(page.locator('.ide-status-language')).toContainText(' · plain · ')
  await row(page, 'accounts').click({ button: 'right' })
  await page.getByRole('menu', { name: 'Actions for accounts', exact: true }).getByRole('menuitem', { name: 'New Java Class', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'New Java Class', exact: true })
  const name = dialog.getByRole('textbox', { name: 'Class name', exact: true })
  await expect(name).toHaveValue('NewClass')
  await name.fill('bad-name')
  await dialog.getByRole('button', { name: 'Create', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('valid Java class name')
  await expect(name).toHaveValue('bad-name')
  await name.fill('Ledger')
  await dialog.getByRole('button', { name: 'Create', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(tab(page, 'accounts/Ledger.java')).toHaveAttribute('aria-selected', 'true')
  const file = await request.get(`/api/projects/${id}/files?path=accounts%2FLedger.java`)
  expect(file.ok()).toBe(true)
  expect((await file.json()).content).toBe('package accounts;\n\npublic class Ledger {\n}\n')
})
