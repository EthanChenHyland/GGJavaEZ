import { expect, test } from '@playwright/test'

test('visible zoom controls reset each representation without changing runtime state', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('slider', { name: 'Scrub execution' }).fill('18')
  for (const representation of ['Classic', 'Spatial']) {
    await page.getByRole('button', { name: representation, exact: true }).click()
    await page.getByRole('button', { name: 'Overview', exact: true }).click()
    await page.waitForTimeout(200)
    const drawing = representation === 'Classic' ? page.locator('.classic-runtime') : page.locator('.world-canvas canvas')
    const baseline = await drawing.screenshot()
    await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
    await page.waitForTimeout(200)
    expect((await drawing.screenshot()).equals(baseline)).toBe(false)
    await expect(page.getByRole('button', { name: 'Follow execution', exact: true })).toHaveAttribute('aria-pressed', 'false')
    for (let n = 0; n < 12; n++) await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
    for (let n = 0; n < 20; n++) await page.getByRole('button', { name: 'Zoom out', exact: true }).click()
    await page.getByRole('button', { name: 'Reset view', exact: true }).click()
    await page.waitForTimeout(200)
    expect((await drawing.screenshot()).equals(baseline)).toBe(true)
    await expect(page.locator('.vj-timeline__count')).toContainText('18 / 21')
  }
})

test('Classic slots and reference arrows select the shared inspector; switching preserves viewport', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('slider', { name: 'Scrub execution' }).fill('18')
  await page.getByRole('button', { name: 'Classic', exact: true }).click()
  await page.getByRole('button', { name: 'Overview', exact: true }).click()
  await page.getByRole('button', { name: 'Heap object Person #17', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Person #17' })).toBeVisible()
  await page.getByRole('button', { name: 'Close inspector' }).click()
  await page.getByRole('button', { name: 'main() p points to Person #17', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Reference path' })).toBeVisible()
  await page.getByRole('button', { name: 'Close inspector' }).click()
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  const view = await page.locator('.classic-runtime').getAttribute('viewBox')
  await page.getByRole('button', { name: 'Spatial', exact: true }).click()
  await page.getByRole('button', { name: 'Zoom out', exact: true }).click()
  await page.getByRole('button', { name: 'Classic', exact: true }).click()
  await expect(page.locator('.classic-runtime')).toHaveAttribute('viewBox', view!)
  await expect(page.getByRole('button', { name: 'Theater', exact: true })).toBeDisabled()
})
