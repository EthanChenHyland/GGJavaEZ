import {selectRecording} from './reference/menuActions'
import { expect, test } from '@playwright/test'

const cursor = (page: import('@playwright/test').Page) => page.getByRole('slider', { name: 'Scrub execution' })
async function recursion(page: import('@playwright/test').Page) {
  await page.goto('/examples')
  await selectRecording(page,'recursion')
  await expect(page.locator('.vj-timeline__count')).toContainText('0 / 36')
}

test('six invocations, operands, and return values stay synchronized across representations', async ({ page }) => {
  await recursion(page)
  await cursor(page).fill('19')
  await page.getByLabel('Select runtime entity').selectOption('frame:factorial:3')
  await expect(page.getByRole('heading', { name: 'Main.factorial(3)', exact: true })).toBeVisible()
  await expect(page.locator('.inspector-row').filter({ hasText: /^nint/ })).toContainText('3')
  for (const view of ['Classic', 'Spatial', 'Classic', 'Spatial']) {
    await page.getByRole('button', { name: view, exact: true }).click()
    await expect(cursor(page)).toHaveValue('19')
    await expect(page.getByLabel('Select runtime entity')).toHaveValue('frame:factorial:3')
    await expect(page.locator('.call-status')).toContainText('6 LIVE FRAMES')
    await expect(page.locator('.monaco-editor .executing-line')).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Main.factorial(3)', exact: true })).toBeVisible()
  }
  await page.getByRole('button', { name: 'Classic', exact: true }).click()
  await expect(page.locator('.classic-runtime [data-runtime-kind="frame"]')).toHaveCount(6)
  await page.getByRole('button', { name: 'Next event' }).click()
  await expect(page.locator('.call-status')).toContainText('1 returns1')
  await expect(page.locator('.classic-runtime')).toContainText('factorial(1) returns 1')
  await page.getByRole('button', { name: 'Next event' }).click()
  await expect(page.locator('.classic-runtime [data-runtime-kind="frame"]')).toHaveCount(6)
  await expect(page.locator('.classic-runtime [data-runtime-id="frame:factorial:1"]')).toHaveAttribute('data-invocation-status', 'completed')
  await cursor(page).fill('19')
  await expect(page.locator('.classic-runtime [data-runtime-kind="frame"]')).toHaveCount(6)
  await expect(page.locator('.return-history')).toHaveCount(0)
  await cursor(page).fill('26')
  await expect(page.locator('.call-status')).toContainText('3 × 2')
  await expect(page.locator('.classic-runtime')).toContainText('factorial(3) returns 6')
  await expect(page.locator('.inspector')).toContainText('RETURN VALUE6')
  await page.locator('.classic-runtime [data-slot-id="return:frame:factorial:3"]').click()
  await expect(page.getByRole('heading', { name: 'return', exact: true })).toBeVisible()
  await expect(page.locator('.inspector')).toContainText('VALUE6')
})

test('recursion stops naturally, retains final result, and replays without looping', async ({ page }) => {
  await recursion(page)
  await page.getByLabel('Playback speed').selectOption('4')
  await page.getByRole('button', { name: 'Play execution', exact: true }).click()
  await page.getByRole('button', { name: 'Classic', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Pause execution', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Spatial', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Replay execution', exact: true })).toBeVisible({ timeout: 10000 })
  await expect(cursor(page)).toHaveValue('36')
  await expect(page.locator('.final-result')).toHaveText('result = 120')
  await expect(page.locator('.return-history')).toHaveText('5 returns12624120')
  await expect(page.getByRole('button', { name: 'Next event', exact: true })).toBeDisabled()
  await page.waitForTimeout(600)
  await expect(cursor(page)).toHaveValue('36')
  await page.getByRole('button', { name: 'Previous event', exact: true }).click()
  await expect(cursor(page)).toHaveValue('35')
  await cursor(page).fill('36')
  await page.getByRole('button', { name: 'Replay execution', exact: true }).click()
  await expect(cursor(page)).toHaveValue('0')
  await page.getByRole('button', { name: 'Pause execution', exact: true }).click()
  await cursor(page).fill('0')
  await expect(page.locator('.call-status')).toContainText('0 LIVE FRAMES')
  await cursor(page).fill('36')
  await expect(page.locator('.final-result')).toHaveText('result = 120')
})

test('recursive free navigation overrides Follow while playback continues and Focus/Home recover', async ({ page }) => {
  await recursion(page)
  await cursor(page).fill('14')
  await page.getByRole('button', { name: 'Play execution', exact: true }).click()
  await page.mouse.move(900, 430)
  await page.mouse.down()
  await page.mouse.move(970, 465, { steps: 10 })
  await page.mouse.up()
  await expect(page.getByRole('button', { name: 'Follow execution', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByRole('button', { name: 'Pause execution', exact: true })).toBeVisible()
  await expect.poll(async () => Number(await cursor(page).inputValue())).toBeGreaterThan(14)
  await cursor(page).fill('19')
  await page.getByLabel('Select runtime entity').selectOption('frame:factorial:3')
  await page.getByRole('button', { name: 'Focus selected entity', exact: true }).click()
  await expect(page.locator('.world-label')).toContainText('FOCUS ENTITY')
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  await page.getByRole('button', { name: 'Overview', exact: true }).click()
  await expect(page.locator('.world-label')).toContainText('HOME')
  await expect(cursor(page)).toHaveValue('19')
  await page.getByRole('button', { name: 'Follow execution', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Follow execution', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

test('returned invocation remains inspectable; example switching restores Person without stale source or selection', async ({ page }) => {
  await recursion(page)
  await cursor(page).fill('19')
  await page.getByLabel('Select runtime entity').selectOption('frame:factorial:1')
  await cursor(page).fill('21')
  await expect(page.locator('.inspector')).toContainText('RETURNED')
  await expect(page.locator('.inspector')).toContainText('RETURN VALUE1')
  await page.setViewportSize({ width: 760, height: 900 })
  await page.getByRole('button', { name: 'Close inspector', exact: true }).click()
  await expect(page.getByLabel('Runtime inspector')).toHaveCount(0)
  await page.setViewportSize({ width: 1440, height: 900 })
  await selectRecording(page,'person')
  await expect(cursor(page)).toHaveValue('0')
  await expect(page.getByLabel('Runtime inspector')).toHaveCount(0)
  await cursor(page).fill('18')
  await page.getByLabel('Select runtime entity').selectOption('object:person:17')
  await expect(page.getByRole('heading', { name: 'Person #17', exact: true })).toBeVisible()
  await expect(page.locator('.inspector-row').filter({ hasText: 'age' })).toContainText('18')
  await expect(page.locator('.monaco-editor')).toContainText('class Person')
})
